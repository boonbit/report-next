package report

import (
	"archive/zip"
	"bytes"
	"io"
	"net/http"
	"net/http/httptest"
	"strings"
	"testing"
)

func unzipDoc(t *testing.T, data []byte) string {
	t.Helper()
	zr, err := zip.NewReader(bytes.NewReader(data), int64(len(data)))
	if err != nil {
		t.Fatal(err)
	}
	f, err := zr.Open("word/document.xml")
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	body, err := io.ReadAll(f)
	if err != nil {
		t.Fatal(err)
	}
	return string(body)
}

func TestDOCXExportHello(t *testing.T) {
	out, err := docxExportReport(loadHello(t))
	if err != nil {
		t.Fatal(err)
	}
	body := unzipDoc(t, out)
	for _, want := range []string{"The report goes here", "Generated by report-next", "<w:b/>"} {
		if !strings.Contains(body, want) {
			t.Errorf("docx missing %q", want)
		}
	}
}

func TestDOCXExportTable(t *testing.T) {
	out, err := docxExportReport(loadFile(t, "table.frx"))
	if err != nil {
		t.Fatal(err)
	}
	body := unzipDoc(t, out)
	if !strings.Contains(body, "<w:tbl>") {
		t.Error("table.frx produced no docx table")
	}
}

func TestSrvDOCXRoute(t *testing.T) {
	raw, err := MarshalJSON(loadHello(t))
	if err != nil {
		t.Fatal(err)
	}
	res := httptest.NewRecorder()
	SrvMux(&DataDictionary{}).ServeHTTP(res,
		httptest.NewRequest(http.MethodPost, "/api/docx", bytes.NewReader(raw)))
	if res.Code != http.StatusOK {
		t.Fatalf("status = %d", res.Code)
	}
	if ct := res.Header().Get("Content-Type"); ct != "application/vnd.openxmlformats-officedocument.wordprocessingml.document" {
		t.Fatalf("content-type = %q", ct)
	}
	if !strings.Contains(unzipDoc(t, res.Body.Bytes()), "The report goes here") {
		t.Fatal("served docx missing text")
	}
}
