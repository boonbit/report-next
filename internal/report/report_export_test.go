package report

import (
	"reflect"
	"strings"
	"testing"
)

// TestXlsxReportHello exports hello.frx with a nil dict: the workbook must
// unzip to a valid sheet containing the report's known static text.
func TestXlsxReportHello(t *testing.T) {
	out, err := xlsxExportReport(loadHello(t), nil)
	if err != nil {
		t.Fatal(err)
	}
	sheet := unzipPart(t, out, "xl/worksheets/sheet1.xml")
	for _, want := range []string{"Text", "The report goes here", "Generated by report-next"} {
		if !strings.Contains(sheet, want) {
			t.Errorf("report xlsx sheet missing %q", want)
		}
	}
}

// TestCsvReportHello exports hello.frx with a nil dict: header plus at
// least one data line carrying the known static text.
func TestCsvReportHello(t *testing.T) {
	got := exportCSVReport(loadHello(t), nil)
	lines := strings.Split(strings.TrimSuffix(got, "\n"), "\n")
	if len(lines) < 2 {
		t.Fatalf("csv = %q, want header + data", got)
	}
	if lines[0] != "Text" {
		t.Fatalf("csv header = %q, want %q", lines[0], "Text")
	}
	if !strings.Contains(got, "The report goes here") {
		t.Fatalf("csv missing known text: %q", got)
	}
}

// TestReportExportBound builds a data-bound report over Customers and
// requires the prepared exports to carry evaluated field values, not the
// literal [CompanyName] expression.
func TestReportExportBound(t *testing.T) {
	dict := loadCustomersDict(t)
	rep := exprNewReport("Bound check")
	pi := exprAddPage(rep, "Page1")
	bi := exprAddBand(rep, pi, "DataBand", "Data1")
	rep.Pages[pi].Bands[bi].Attrs = append(rep.Pages[pi].Bands[bi].Attrs,
		Attr{Name: "DataSource", Value: "Customers"})
	exprAddText(rep, pi, bi, "T1", "[CompanyName]")

	if got := exportCSVReport(*rep, dict); !strings.Contains(got, "Alfreds Futterkiste") {
		t.Fatalf("csv did not substitute data:\n%s", got)
	} else if strings.Contains(got, "[CompanyName]") {
		t.Fatalf("csv kept literal expression:\n%s", got)
	}
	out, err := xlsxExportReport(*rep, dict)
	if err != nil {
		t.Fatal(err)
	}
	sheet := unzipPart(t, out, "xl/worksheets/sheet1.xml")
	if !strings.Contains(sheet, "Alfreds Futterkiste") {
		t.Fatal("xlsx did not substitute data")
	}
}

// TestReportExportEmpty requires headers without crashing on a report
// with no pages, and proves neither input is mutated.
func TestReportExportEmpty(t *testing.T) {
	var rep Report
	var dict *DataDictionary
	if got := exportCSVReport(rep, dict); got != "Text\n" {
		t.Fatalf("empty csv = %q, want %q", got, "Text\n")
	}
	out, err := xlsxExportReport(rep, dict)
	if err != nil {
		t.Fatal(err)
	}
	sheet := unzipPart(t, out, "xl/worksheets/sheet1.xml")
	if !strings.Contains(sheet, "Text") {
		t.Fatalf("empty xlsx sheet missing header: %s", sheet)
	}

	full := loadHello(t)
	beforeRep, err := MarshalJSON(full)
	if err != nil {
		t.Fatal(err)
	}
	d := loadCustomersDict(t)
	beforeRows := len(d.Sources[0].Rows)
	beforeCell := d.Sources[0].Rows[0]["CompanyName"]
	if _, err := xlsxExportReport(full, d); err != nil {
		t.Fatal(err)
	}
	_ = exportCSVReport(full, d)
	afterRep, err := MarshalJSON(full)
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(beforeRep, afterRep) {
		t.Error("exports mutated the report")
	}
	if len(d.Sources[0].Rows) != beforeRows || d.Sources[0].Rows[0]["CompanyName"] != beforeCell {
		t.Error("exports mutated the dictionary")
	}
}
